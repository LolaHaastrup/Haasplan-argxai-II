#: Whether the participant agrees with the explanation, asked after the
#: dialogue. The supervisor suggested "do you agree with the explanation" in
#: place of "verdict", which sounds legal. The internal names (VERDICT_ITEM and
#: the verdict_agreement column) are kept so that stored data and the analysis
#: script keep working; only what the participant reads has changed.
#:
#: WHY THIS IS A QUESTIONNAIRE ITEM AND NOT A DIALOGUE MOVE. Adding an "I
#: disagree" locution to the protocol would turn an explanation dialogue into
#: a persuasion dialogue, because the participant would then be advancing a
#: competing claim that the system must answer. The dialogue type is settled
#: and the termination and faithfulness results depend on it. Asking after the
#: dialogue records disagreement without disturbing the formal framework.
